function dishLevel(dish){ return dish.tier * 2 + Math.floor(dish.group / 3); }
function levelTier(level){ return Math.floor(level / 2); }
function levelStartGroup(level){ return (level % 2) * 3; }
function levelEndGroup(level){ return levelStartGroup(level) + 2; }
 
function detectToolsForDish(dish){
  const text = (dish.ingredients + ' ' + dish.steps).toLowerCase();
  return KITCHEN_TOOLS.filter(tool =>
    tool.keywords.some(kw => text.includes(kw.toLowerCase()))
  );
}
